  /// Delete a shopping item locally and queue for sync.
  Future<void> deleteItem(String homeId, String listId, String itemId) async {
    final operationId = _uuid.v4();
    final now = DateTime.now();

    await _runInTransaction(() async {
      // 1. Soft delete locally
      await _shoppingDao.softDeleteShoppingItem(itemId);

      // 2. Enqueue sync
      await _syncDao.addToSyncQueue(SyncQueueEntriesCompanion(
        operationId: Value(operationId),
        operationType: const Value(SyncOperationType.deleteShoppingItem),
        entityType: const Value(SyncEntityType.shoppingListItem),
        entityId: Value(itemId),
        payload: Value(jsonEncode({'listId': listId})),
        createdAt: Value(now),
        homeId: Value(homeId),
      ));
    });

    _syncEngine.trySyncImmediate();
  }

  /// Clear all completed items locally and queue for sync.
  Future<void> clearCompleted(String homeId, String listId) async {
    final operationId = _uuid.v4();
    final now = DateTime.now();

    await _runInTransaction(() async {
      // 1. Delete completed items locally across all home lists
      await _shoppingDao.clearCompletedItemsForHome(homeId);

      // 2. Enqueue sync
      await _syncDao.addToSyncQueue(SyncQueueEntriesCompanion(
        operationId: Value(operationId),
        operationType: const Value(SyncOperationType.clearCompletedShopping),
        entityType: const Value(SyncEntityType.shoppingList),
        entityId: Value(listId),
        payload: Value(jsonEncode({'listId': listId})),
        createdAt: Value(now),
        homeId: Value(homeId),
      ));
    });

    _syncEngine.trySyncImmediate();
  }

  // ──── REMOTE (for initial load) ────

  /// Fetch from server and populate local DB.
  Future<void> fetchAndCacheFromServer(String homeId) async {
    if (homeId.isEmpty || homeId == 'default_home') return;
    if (_connectivity != null && !_connectivity.isOnline) return;
    try {
      final response = await _apiClient.dio
          .get(ApiEndpoints.defaultShoppingList(homeId));
      final data = response.data['data'];
      if (data == null) return;

      final serverListId = data['id'] as String;

      // Upsert the server list
      await _shoppingDao.upsertShoppingList(LocalShoppingListsCompanion(
        id: Value(serverListId),
        homeId: Value(homeId),
        name: Value(data['name'] as String? ?? 'Home Shopping List'),
        isDefault: Value(data['isDefault'] as bool? ?? true),
        updatedAt: Value(DateTime.now()),
      ));

      // If a placeholder local list existed with id == homeId, migrate items to serverListId
      if (serverListId != homeId) {
        await _shoppingDao.migrateItemShoppingListId(homeId, serverListId);
        await _shoppingDao.deleteShoppingListById(homeId);
      }

      // Upsert items
      final rawItems = data['items'] as List? ?? [];
      final companions = rawItems.map((json) {
        return LocalShoppingListItemsCompanion(
          id: Value(json['id'] as String),
          shoppingListId: Value(json['shoppingListId'] as String? ?? serverListId),
          inventoryItemId: Value(json['inventoryItemId'] as String?),
          itemName: Value(json['itemName'] as String? ?? ''),
          categoryName: Value(json['categoryName'] as String?),
          categoryIcon: Value(json['categoryIcon'] as String? ?? 'category'),
          categoryColor: Value(json['categoryColor'] as String? ?? '#6366F1'),
          quantity: Value((json['quantity'] as num?)?.toDouble() ?? 1.0),
          unit: Value(json['unit'] as String? ?? 'pcs'),
          isCompleted: Value(json['isCompleted'] as bool? ?? false),
          isAutoGenerated: Value(json['isAutoGenerated'] as bool? ?? false),
          addedByName: Value(json['addedByName'] as String? ?? ''),
          completedByName: Value(json['completedByName'] as String?),
          completedAt: Value(json['completedAt'] as String?),
          notes: Value(json['notes'] as String?),
          isLocalOnly: const Value(false),
          isDeleted: const Value(false),
          updatedAt: Value(DateTime.now()),
        );
      }).toList();

      await _shoppingDao.upsertShoppingItems(companions);
    } catch (e) {
      if (kDebugMode) print('[ShoppingRepo] Fetch from server failed: $e');
    }
  }
