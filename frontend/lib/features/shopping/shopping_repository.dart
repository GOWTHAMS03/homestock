const _uuid = Uuid();

/// Offline-first shopping repository.
///
/// All reads come from local SQLite.
/// All writes go to local DB + sync queue.
/// Individual operations are synced (not entire list replacement).
class ShoppingRepository {
  final ShoppingDao _shoppingDao;
  final SyncDao _syncDao;
  final ApiClient _apiClient;
  final SyncEngine _syncEngine;
  final ConnectivityMonitor? _connectivity;
  final InventoryDao? _inventoryDao;
  final AppDatabase? _db;

  ShoppingRepository({
    required ShoppingDao shoppingDao,
    required SyncDao syncDao,
    required ApiClient apiClient,
    required SyncEngine syncEngine,
    ConnectivityMonitor? connectivity,
    InventoryDao? inventoryDao,
    AppDatabase? database,
  })  : _shoppingDao = shoppingDao,
        _syncDao = syncDao,
        _apiClient = apiClient,
        _syncEngine = syncEngine,
        _connectivity = connectivity,
        _inventoryDao = inventoryDao,
        _db = database;

  Future<T> _runInTransaction<T>(Future<T> Function() action) async {
    if (_db != null) {
      return _db.transaction(action);
    }
    return action();
  }

  bool get isOnline => _connectivity?.isOnline ?? true;

  // ──── READ (always local) ────

  /// Watch the default shopping list with items as a reactive stream.
  Stream<ShoppingListModel?> watchDefaultList(String homeId) {
    final listStream = _shoppingDao.watchShoppingItemsForHome(homeId);
    return listStream.asyncMap((items) async {
      var list = await _shoppingDao.getDefaultList(homeId);
      list ??= await _shoppingDao.ensureDefaultList(homeId);

      final modelItems = items
          .map((item) => ShoppingItemModel(
                id: item.id,
                shoppingListId: item.shoppingListId,
                inventoryItemId: item.inventoryItemId,
                itemName: item.itemName,
                categoryName: item.categoryName,
                categoryIcon: item.categoryIcon,
                categoryColor: item.categoryColor,
                quantity: item.quantity,
                unit: item.unit,
                isCompleted: item.isCompleted,
                isAutoGenerated: item.isAutoGenerated,
                addedByName: item.addedByName,
                completedByName: item.completedByName,
                completedAt: item.completedAt,
                notes: item.notes,
                barcode: item.barcode,
                productId: item.productId,
              ))
          .toList();

      return ShoppingListModel(
        id: list.id,
        homeId: list.homeId,
        name: list.name,
        isDefault: list.isDefault,
        pendingCount: modelItems.where((i) => !i.isCompleted).length,
        completedCount: modelItems.where((i) => i.isCompleted).length,
        items: modelItems,
      );
    });
  }

  /// Get the default list (non-reactive).
